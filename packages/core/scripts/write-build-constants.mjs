/**
 * Writes browser-safe build metadata for provenance envelopes into
 * src/generated/build-constants.ts. The output is a pure function of
 * packages/core/package.json and the luxon version installed for core, so
 * re-running it is deterministic. The root `pnpm build` and core's `build`
 * both run it before tsc. `--check` exits 1 if the committed file is stale.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const coreRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(coreRoot, 'package.json'), 'utf8'));

// Resolve luxon the way core's own code does. Fail loudly rather than writing
// a placeholder: a missing install would otherwise silently change the file.
const require = createRequire(join(coreRoot, 'package.json'));
const luxonVersion = JSON.parse(readFileSync(require.resolve('luxon/package.json'), 'utf8')).version;

const contents = `/**
 * Generated by scripts/write-build-constants.mjs — do not edit by hand.
 * Regenerated by \`pnpm build\` (root or @node-jhora/core); tests fail if stale.
 */
export const ENGINE_VERSION = '${pkg.version}';
/** Luxon release paired with this build; zones resolve via host Intl. */
export const TZDB_VERSION = 'luxon-${luxonVersion}';
`;

const outDir = join(coreRoot, 'src', 'generated');
const outFile = join(outDir, 'build-constants.ts');
const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;

if (process.argv.includes('--check')) {
    if (current !== contents) {
        console.error(`${outFile} is stale; run \`pnpm build\`.`);
        process.exit(1);
    }
} else if (current !== contents) {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(outFile, contents, 'utf8');
}
