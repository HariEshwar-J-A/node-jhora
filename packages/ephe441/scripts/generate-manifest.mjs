#!/usr/bin/env node
/**
 * Regenerate the DE441 ephemeris integrity manifest shipped in @node-jhora/core.
 *
 *   node packages/ephe441/scripts/generate-manifest.mjs [chunkDir]
 *
 * Writes packages/core/src/ephemeris-data/manifest.de441.generated.ts.
 */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '../../..');
const chunkDir = process.argv[2] ?? process.env.NJCE441_DIR ?? join(here, '../dist');
const out = join(repo, 'packages/core/src/ephemeris-data/manifest.de441.generated.ts');

const rows = [];
for (let century = -100; century <= 100; century++) {
    for (const groupId of [0, 1]) {
        const path = join(chunkDir, `g${groupId}-c${century}.njce`);
        if (!existsSync(path)) {
            console.error(`missing ${path}`);
            process.exit(1);
        }
        const bytes = readFileSync(path);
        const sha256 = createHash('sha256').update(bytes).digest('hex');
        rows.push(`    [${century}, ${groupId}, ${bytes.length}, '${sha256}'],`);
    }
}

const body = `/**
 * GENERATED by packages/ephe441/scripts/generate-manifest.mjs — do not edit.
 *
 * SHA-256 and byte length of every NJCE chunk built from JPL DE441
 * (de441_part-1.bsp + de441_part-2.bsp) by packages/ephe441/scripts/build-chunks.mjs.
 * Row layout: [century, groupId, bytes, sha256].
 */

export const NJCE441_CHUNK_ROWS: ReadonlyArray<readonly [number, number, number, string]> = [
${rows.join('\n')}
];
`;
writeFileSync(out, body);
console.log(`wrote ${rows.length} DE441 chunk entries to ${out}`);
