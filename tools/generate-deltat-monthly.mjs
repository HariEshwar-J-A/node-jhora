#!/usr/bin/env node
/**
 * Regenerate packages/core/src/engine/deltat-monthly.ts from USNO deltat.data.
 * Source: https://maia.usno.navy.mil/ser7/deltat.data (IERS Bulletin B).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/core/src/engine/deltat-monthly.ts');

const url = 'https://maia.usno.navy.mil/ser7/deltat.data';
const curl = spawnSync('curl', ['-sS', url], { encoding: 'utf8' });
if (curl.status !== 0) {
    console.error(curl.stderr);
    process.exit(1);
}

const rows = [];
for (const line of curl.stdout.split('\n')) {
    const m = line.trim().match(/^(\d{4})\s+(\d{1,2})\s+1\s+([\d.]+)/);
    if (!m) continue;
    const year = Number(m[1]);
    const month = Number(m[2]);
    const dt = Number(m[3]);
    const y = year + (month - 1) / 12;
    rows.push([y, dt]);
}

rows.sort((a, b) => a[0] - b[0]);

const body = `/**
 * @provenance U.S. Naval Observatory Earth Orientation Department,
 * observed monthly ΔT file "deltat.data" (ΔT = (TAI−UTC)−(UT1−UTC)+32.184 s),
 * https://maia.usno.navy.mil/ser7/deltat.data — generated by tools/generate-deltat-monthly.mjs
 *
 * Each row is [decimal year, ΔT seconds] at the first day of the month.
 * Swiss Ephemeris 2.10 uses this series (from 1974 onward per the SE manual) with
 * linear interpolation between tabulated months.
 */
export const DELTAT_MONTHLY: readonly (readonly [number, number])[] = [
${rows.map(([y, dt]) => `    [${y}, ${dt}],`).join('\n')}
];

export const DELTAT_MONTHLY_FIRST = DELTAT_MONTHLY[0][0];
export const DELTAT_MONTHLY_LAST = DELTAT_MONTHLY[DELTAT_MONTHLY.length - 1][0];
`;

writeFileSync(OUT, body);
console.log('wrote', rows.length, 'rows to', OUT);
